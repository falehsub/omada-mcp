#!/usr/bin/env python3
"""Generate docs/tools-reference.md from TOOLS descriptors and verify zero doc/metadata drift."""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any

_SCRIPTS_DIR = Path(__file__).resolve().parent
_ROOT_DIR = _SCRIPTS_DIR.parent
sys.path.insert(0, str(_ROOT_DIR / "src"))

from omada_mcp import __version__ as PACKAGE_VERSION  # noqa: E402
from omada_mcp.config import _READ_ONLY_TOOL_NAMES, WRITE_TOOL_NAMES  # noqa: E402
from omada_mcp.tools import TOOLS, Tool  # noqa: E402

_VERSION_RE = re.compile(r'^\s*version\s*=\s*"([^"]+)"', re.MULTILINE)


def read_pyproject_version(root: Path) -> str:
    """Return ``[project].version`` from pyproject.toml cleanly across Python 3.10+."""
    text = (root / "pyproject.toml").read_text(encoding="utf-8")
    in_project = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            in_project = stripped == "[project]"
            continue
        if in_project:
            m = _VERSION_RE.match(line)
            if m:
                return m.group(1)
    raise ValueError("could not find [project].version in pyproject.toml")


def _escape_md(text: str) -> str:
    clean = " ".join(str(text or "").strip().split())
    return clean.replace("|", "\\|")


def _format_params(tool: Tool) -> str:
    schema = tool.input_schema or {}
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    if not props:
        return "—"
    ordered = [k for k in props if k in required] + [
        k for k in props if k not in required and k not in ("dryRun", "confirm", "site")
    ]
    for tail in ("dryRun", "confirm", "site"):
        if tail in props and tail not in ordered:
            ordered.append(tail)
    parts: list[str] = []
    for name in ordered:
        if name in required:
            parts.append(f"**`{name}`**")
        else:
            parts.append(f"`{name}?`")
    return ", ".join(parts)


def _format_flags(tool: Tool) -> str:
    tier_flags: list[str] = [
        f"readOnly={str(tool.read_only).lower()}",
        f"destructive={str(tool.destructive).lower()}",
        f"idempotent={str(tool.idempotent).lower()}",
    ]
    if not tool.requires_auth:
        tier_flags.append("offline")
    if not tool.site_scoped:
        tier_flags.append("global")
    return ", ".join(tier_flags)


def render_tools_reference(root: Path) -> str:
    """Render the deterministic Markdown reference covering every descriptor in TOOLS."""
    ro_tools = [t for t in TOOLS if t.read_only]
    wr_tools = [t for t in TOOLS if not t.read_only]
    cat_ro = Counter(t.category for t in ro_tools)
    cat_wr = Counter(t.category for t in wr_tools)
    categories = sorted(set(cat_ro) | set(cat_wr))

    lines: list[str] = [
        "<!-- GENERATED BY scripts/generate_docs.py; DO NOT EDIT MANUALLY -->",
        "",
        "# Tool & Configuration Reference",
        "",
        (
            f"Generated directly from `omada_mcp.tools.TOOLS` (**{len(TOOLS)} total**: "
            f"**{len(ro_tools)} read-only**, **{len(wr_tools)} opt-in write**)."
        ),
        "",
        "- Required parameters are shown in **`bold`**; optional parameters carry `?`.",
        "- Site-scoped tools accept optional `site?` (pinned when `OMADA_SITE_NAME`/`OMADA_SITE_ID` is set unless `OMADA_ALLOW_CROSS_SITE=true`).",
        "- Write tools require `OMADA_READ_ONLY=false` and explicit `OMADA_WRITE_TOOLS` allowlisting. Preview with `dryRun=true`, then pass the single-use `confirmToken` as `confirm` with `dryRun=false` in the same server session.",
        "",
        "## Category Breakdown",
        "",
        "| Category | Read-only | Opt-in write | Total |",
        "|---|---:|---:|---:|",
    ]
    for cat in categories:
        r_cnt = cat_ro[cat]
        w_cnt = cat_wr[cat]
        lines.append(f"| `{cat}` | {r_cnt} | {w_cnt} | {r_cnt + w_cnt} |")

    for heading, subset, tier_label in (
        ("Read-Only Tools", ro_tools, "read-only"),
        ("Opt-In Write Tools", wr_tools, "opt-in write"),
    ):
        lines.extend([
            "",
            f"## {heading} ({len(subset)})",
            "",
            "| Tool | Tier | Category | Hints | Parameters | Description |",
            "|---|---|---|---|---|---|",
        ])
        for tool in subset:
            lines.append(
                f"| `{tool.name}` | {tier_label} | `{tool.category}` | "
                f"`{_format_flags(tool)}` | {_format_params(tool)} | "
                f"{_escape_md(tool.description)} |"
            )

    server_path = root / "server.json"
    if server_path.is_file():
        server_meta: dict[str, Any] = json.loads(server_path.read_text(encoding="utf-8"))
        pkgs = server_meta.get("packages") or []
        env_vars = pkgs[0].get("environmentVariables") or [] if pkgs else []
        if env_vars:
            lines.extend([
                "",
                "## Environment Variables (`server.json`)",
                "",
                "| Variable | Required | Secret | Purpose |",
                "|---|---|---|---|",
            ])
            for var in env_vars:
                req = "yes" if var.get("isRequired") else "no"
                sec = "yes" if var.get("isSecret") else "no"
                lines.append(
                    f"| `{var['name']}` | {req} | {sec} | {_escape_md(str(var.get('description') or ''))} |"
                )

    lines.append("")
    return "\n".join(lines)


def verify_repo_sync(root: Path) -> list[str]:
    """Return a list of documentation, manifest, and count drift errors."""
    errors: list[str] = []

    ro_tools = [t for t in TOOLS if t.read_only]
    wr_tools = [t for t in TOOLS if not t.read_only]
    if {t.name for t in ro_tools} != _READ_ONLY_TOOL_NAMES:
        errors.append("config._READ_ONLY_TOOL_NAMES does not match read_only tools in TOOLS")
    if set(WRITE_TOOL_NAMES) != {t.name for t in wr_tools}:
        errors.append("config.WRITE_TOOL_NAMES does not match write tools in TOOLS")

    try:
        pyproject_ver = read_pyproject_version(root)
    except ValueError as exc:
        errors.append(str(exc))
        pyproject_ver = ""

    if pyproject_ver and pyproject_ver != PACKAGE_VERSION:
        errors.append(
            f"version mismatch: pyproject.toml={pyproject_ver!r} != omada_mcp.__version__={PACKAGE_VERSION!r}"
        )

    server_path = root / "server.json"
    if not server_path.is_file():
        errors.append("missing server.json")
    else:
        try:
            srv = json.loads(server_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            errors.append(f"invalid JSON in server.json: {exc}")
            srv = {}
        if srv:
            for key in ("$schema", "name", "title", "description", "version", "repository", "packages"):
                if not srv.get(key):
                    errors.append(f"server.json missing required field {key!r}")
            desc = str(srv.get("description") or "")
            if len(desc) > 100:
                errors.append(f"server.json description exceeds 100 chars ({len(desc)})")
            if pyproject_ver and srv.get("version") != pyproject_ver:
                errors.append(
                    f"server.json version {srv.get('version')!r} != pyproject.toml {pyproject_ver!r}"
                )
            pkgs = srv.get("packages") or []
            reg_types = {p.get("registryType"): p for p in pkgs if isinstance(p, dict)}
            if "pypi" not in reg_types:
                errors.append("server.json missing pypi package entry")
            elif pyproject_ver and reg_types["pypi"].get("version") != pyproject_ver:
                errors.append("server.json pypi package version does not match pyproject.toml")
            if "oci" in reg_types and pyproject_ver:
                expected_tag = f":{pyproject_ver}"
                ident = str(reg_types["oci"].get("identifier") or "")
                if not ident.endswith(expected_tag):
                    errors.append(f"server.json oci identifier {ident!r} must end with {expected_tag!r}")
            for pkg in pkgs:
                if (pkg.get("transport") or {}).get("type") != "stdio":
                    errors.append(f"server.json package {pkg.get('registryType')} must declare stdio transport")

    ref_path = root / "docs" / "tools-reference.md"
    expected_ref = render_tools_reference(root)
    if not ref_path.is_file():
        errors.append("missing docs/tools-reference.md (run `python scripts/generate_docs.py`)")
    else:
        actual_ref = ref_path.read_text(encoding="utf-8")
        if actual_ref != expected_ref:
            errors.append("docs/tools-reference.md is out of date (run `python scripts/generate_docs.py`)")

    readme_path = root / "README.md"
    if not readme_path.is_file():
        errors.append("missing README.md")
    else:
        readme = readme_path.read_text(encoding="utf-8")
        if "mcp-name: io.github.falehsub/omada-mcp" not in readme:
            errors.append("README.md missing MCP Registry ownership tag `mcp-name: io.github.falehsub/omada-mcp`")
        if f"{len(ro_tools)} read-only" not in readme:
            errors.append(f"README.md missing `{len(ro_tools)} read-only` tool count")
        if f"{len(wr_tools)} optional write" not in readme:
            errors.append(f"README.md missing `{len(wr_tools)} optional write` tool count")
        if str(len(TOOLS)) not in readme:
            errors.append(f"README.md missing `{len(TOOLS)}` total tool count")
        for tool in TOOLS:
            if f"`{tool.name}`" not in readme:
                errors.append(f"README.md does not mention tool `{tool.name}`")

    env_path = root / ".env.example"
    if not env_path.is_file():
        errors.append("missing .env.example")
    else:
        env_text = env_path.read_text(encoding="utf-8")
        for wr_name in WRITE_TOOL_NAMES:
            if wr_name not in env_text:
                errors.append(f".env.example missing write tool name {wr_name!r}")
        if server_path.is_file():
            srv_data = json.loads(server_path.read_text(encoding="utf-8"))
            pypi_pkg = next((p for p in srv_data.get("packages") or [] if p.get("registryType") == "pypi"), None)
            if pypi_pkg:
                for env_var in pypi_pkg.get("environmentVariables") or []:
                    name = str(env_var.get("name") or "")
                    if name and name not in env_text:
                        errors.append(f".env.example missing server.json env var {name!r}")

    for doc_name in ("SECURITY.md", "CONTRIBUTING.md"):
        doc_path = root / doc_name
        if not doc_path.is_file() or not doc_path.read_text(encoding="utf-8").strip():
            errors.append(f"missing or empty {doc_name}")

    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify docs/tools-reference.md, README.md, .env.example, and server.json have zero drift",
    )
    args = parser.parse_args(argv)

    if args.check:
        errors = verify_repo_sync(_ROOT_DIR)
        if errors:
            for err in errors:
                print(f"DRIFT: {err}", file=sys.stderr)
            return 1
        print(f"OK: {len(TOOLS)} tools, docs, .env.example, and server.json are in sync.")
        return 0

    out_path = _ROOT_DIR / "docs" / "tools-reference.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    rendered = render_tools_reference(_ROOT_DIR)
    out_path.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {out_path.relative_to(_ROOT_DIR)} ({len(TOOLS)} tools).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
